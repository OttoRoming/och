/// Terminal bell
pub const BEL: &str = "\x07";
/// Backspace
pub const BS: &str = "\x08";
/// Horizontal TAB
pub const HT: &str = "\x09";
/// Linefeed (newline)
pub const LF: &str = "\x0A";
/// Vertical TAB
pub const VT: &str = "\x0B";
/// Formfeed (New page)
pub const FF: &str = "\x0C";
/// Carriage return
pub const CR: &str = "\x0D";
/// Escape character
pub const ESC: &str = "\x1B";
/// Delete character
pub const DEL: &str = "\x7F";
